#method : 1 using python built-in sum() function
arr = [10, 20, 30, 40, 50]
total = sum(arr)
print("The sum of all elements in the array is:", total)


#method : 2 using simple loop
arr = [10, 20, 30, 40, 50]
total = 0
for num in arr:
    total += num
print("The sum of all elements in the array is:", total)
